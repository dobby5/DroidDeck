#!/usr/bin/env python3
"""Builds app/src/main/assets/switch-titles.tsv from titledb (https://github.com/blawar/titledb, MIT).

Usage: python3 tools/switch-titles/build_index.py <titledb-commit-sha> <US.en.json> [<GB.en.json> ...]

Only base games (title id 01... for Switch, 04... for Switch 2, ending in 000) with an icon on Nintendo's eShop
image server are kept.
Columns: title id, name, icon hash, banner hash (images: https://img-eshop.cdn.nintendo.net/i/<hash>.jpg).
The first region file wins for names; later files only add titles that are missing.
"""
import json, re, sys, pathlib

CDN = re.compile(r"^https://img-eshop\.cdn\.nintendo\.net/i/([0-9a-f]{64})\.jpg$")

def main():
    sha, files = sys.argv[1], sys.argv[2:]
    if not re.fullmatch(r"[0-9a-f]{40}", sha) or not files:
        sys.exit(__doc__)
    rows = {}
    for path in files:
        data = json.load(open(path, encoding="utf-8"))
        for entry in data.values():
            tid = (entry.get("id") or "").upper()
            # Switch (01...) and Switch 2 (04...) base games.
            if not re.fullmatch(r"0[14][0-9A-F]{11}000", tid) or tid in rows:
                continue
            icon = CDN.match(entry.get("iconUrl") or "")
            if not icon:
                continue
            banner = CDN.match(entry.get("bannerUrl") or "")
            name = re.sub(r"[\t\r\n]+", " ", entry.get("name") or "").strip()
            if name:
                rows[tid] = (name, icon.group(1), banner.group(1) if banner else "")
    out = pathlib.Path(__file__).resolve().parents[2] / "app/src/main/assets/switch-titles.tsv"
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write(f"# Nintendo Switch and Switch 2 title index for DroidDeck cover lookup. Generated by tools/switch-titles/build_index.py\n")
        f.write(f"# from titledb commit {sha} (https://github.com/blawar/titledb, MIT License, Copyright (c) 2019 Blake Warner; see switch-titles.LICENSE.txt).\n")
        f.write("# Columns: titleId<TAB>name<TAB>iconHash<TAB>bannerHash; image = https://img-eshop.cdn.nintendo.net/i/<hash>.jpg\n")
        for tid in sorted(rows):
            name, icon, banner = rows[tid]
            f.write(f"{tid}\t{name}\t{icon}\t{banner}\n")
    print(f"{len(rows)} titles -> {out}")

if __name__ == "__main__":
    main()
